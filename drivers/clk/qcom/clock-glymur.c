static ulong glymur_set_rate(struct clk *clk, ulong rate)
{
	struct msm_clk_priv *priv = dev_get_priv(clk->dev);
	const struct freq_tbl *freq;

	switch (clk->id) {
	case GCC_QUPV3_WRAP2_S5_CLK: /* UART21 */
		freq = qcom_find_freq(ftbl_gcc_qupv3_wrap2_s5_clk_src, rate);
		clk_rcg_set_rate_mnd(priv->base, 0xb43f0,
				     freq->pre_div, freq->m, freq->n, freq->src, 16);
		return freq->freq;
	case GCC_PCIE_5_AUX_CLK:
		freq = qcom_find_freq(ftbl_gcc_pcie_aux_clk_src, rate);
		clk_rcg_set_rate_mnd(priv->base, 0xc30a0,
				     freq->pre_div, freq->m, freq->n, freq->src, 16);
		return freq->freq;
	case GCC_PCIE_PHY_5_AUX_CLK:
		freq = qcom_find_freq(ftbl_gcc_pcie_aux_clk_src, rate);
		clk_rcg_set_rate_mnd(priv->base, 0xd2018,
				     freq->pre_div, freq->m, freq->n, freq->src, 16);
		return freq->freq;
	case GCC_PCIE_5_PHY_RCHNG_CLK:
		freq = qcom_find_freq(ftbl_gcc_pcie_phy_rchng_clk_src, rate);
		/* clk_rcg_set_rate() takes the plain divider, the table holds 2 * div - 1 */
		clk_rcg_set_rate(priv->base, 0xc3084, (freq->pre_div + 1) / 2, freq->src);
		return freq->freq;
	default:
		return 0;
	}
}

