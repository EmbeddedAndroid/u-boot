static int glymur_enable(struct clk *clk)
{
	struct msm_clk_priv *priv = dev_get_priv(clk->dev);

	switch (clk->id) {
	case GCC_PCIE_5_PIPE_CLK:
		/* GCC_PCIE_5_PIPE_CLK_SRC: select the PHY pipe clock */
		clk_phy_mux_enable(priv->base, 0xc309c, true);
		break;
	}

	return qcom_gate_clk_en(priv, clk->id);
}

